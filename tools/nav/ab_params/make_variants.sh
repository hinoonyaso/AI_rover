#!/usr/bin/env bash
# 한글: 직진 흔들림 A/B 시험 전용 파라미터 파일을 설치된 nav2_params.yaml에서 만든다(기본 설정은 안 바꿈).
#   두 파일 모두 BaseObstacle.scale 0.1 -> 0.02 (좁은 방에서 DWB가 전진 대신 제자리를 고르던 것 제거, troubleshooting/031)
#   wobble_limited  : A = LimitedAccelGenerator (현재 기본)
#   wobble_standard : C = StandardTrajectoryGenerator + vy_samples 10 (2026-10-07 이전)
# Usage: make_variants.sh, then
#   ros2 launch jetrover_navigation nav2.launch.py params_file:=$HOME/jetrover_ws/tools/nav/ab_params/nav2_params_wobble_limited.yaml
set -euo pipefail
src=~/jetrover_ws/install/jetrover_navigation/share/jetrover_navigation/config/nav2_params.yaml
dir=$(cd "$(dirname "$0")" && pwd)
test_only='s|^\(\s*\)BaseObstacle.scale: 0.1 .*|\1BaseObstacle.scale: 0.02  # WOBBLE TEST ONLY (default 0.1)|'
sed -e "$test_only" "$src" > "$dir/nav2_params_wobble_limited.yaml"
sed -e "$test_only" \
    -e 's|trajectory_generator_name: "dwb_plugins::LimitedAccelGenerator"|trajectory_generator_name: "dwb_plugins::StandardTrajectoryGenerator"|' \
    -e 's|^\(\s*\)vy_samples: 11 .*|\1vy_samples: 10  # A/B variant: pre-2026-10-07 value|' \
    "$src" > "$dir/nav2_params_wobble_standard.yaml"
for f in wobble_limited wobble_standard; do
  echo "== $f"; diff "$src" "$dir/nav2_params_$f.yaml" | grep '^>' || true
done
rm -f "$dir/nav2_params_standard_gen.yaml"

# MPPI variant (2026-10-09): FollowPath keeps the RotationShim keys, DWB keys are replaced by config/mppi_followpath.yaml
# 한글: FollowPath에서 shim 설정은 유지하고 DWB 설정만 MPPI로 교체
python3 - "$src" "$(dirname "$src")/mppi_followpath.yaml" "$dir/nav2_params_mppi.yaml" <<'PY'
import sys, yaml
base, mppi, out = sys.argv[1:4]
d = yaml.safe_load(open(base))
fp = d['controller_server']['ros__parameters']['FollowPath']
shim_keys = ['plugin', 'angular_dist_threshold', 'angular_disengage_threshold', 'forward_sampling_distance',
             'rotate_to_heading_angular_vel', 'max_angular_accel', 'simulate_ahead_time',
             'rotate_to_goal_heading', 'rotate_to_heading_once', 'use_path_orientations']
new = {k: fp[k] for k in shim_keys if k in fp}
new.update(yaml.safe_load(open(mppi)))
d['controller_server']['ros__parameters']['FollowPath'] = new
open(out, 'w').write('# GENERATED by make_variants.sh from nav2_params.yaml + mppi_followpath.yaml -- do not edit\n'
                     + yaml.safe_dump(d, sort_keys=False))
print('wrote', out)
# A/B for the 45 deg limit (2026-10-10): same MPPI with LateralRatioCritic disabled
# 한글: LateralRatioCritic만 끈 비교용(시뮬레이션 시나리오 tools/sim/run_scenarios.sh)
new['LateralRatioCritic']['enabled'] = False
out2 = out.replace('_mppi.yaml', '_mppi_nolr.yaml')
open(out2, 'w').write('# GENERATED by make_variants.sh: nav2_params_mppi.yaml with LateralRatioCritic off -- do not edit\n'
                      + yaml.safe_dump(d, sort_keys=False))
print('wrote', out2)
# V1 (2026-10-11): VelocityDeadbandCritic off. The old motor dead zone (0.006 m/s did not turn the wheels, vendor firmware)
# is gone with the own firmware (0.02 m/s tracked at ratio 1.00), and the critic was suspected of the 10-20 s dithering in front
# of the box (vx ~ 0, vy sign flips) seen in the DWB vs MPPI B trials. Single change vs nav2_params_mppi.yaml.
# 한글: V1 = VelocityDeadbandCritic 끔. 자체 펌웨어에서 모터 데드존이 사라졌고, 상자 앞 망설임의 의심 원인.
new['LateralRatioCritic']['enabled'] = True
new['VelocityDeadbandCritic']['enabled'] = False
out3 = out.replace('_mppi.yaml', '_mppi_nodb.yaml')
open(out3, 'w').write('# GENERATED by make_variants.sh: nav2_params_mppi.yaml with VelocityDeadbandCritic off -- do not edit\n'
                      + yaml.safe_dump(d, sort_keys=False))
print('wrote', out3)
# TOL010 (2026-10-11): goal tolerance 0.15 -> 0.10 m with the DWB RotateToGoal tolerance kept below it (0.12 -> 0.08,
# the 2026-10-07 lesson: the controller's own tolerance larger than the goal checker's parks the robot short).
# Everything else = nav2_params.yaml (DWB default). 한글: goal 허용 오차만 줄인 DWB 변형(내부 허용 오차도 함께 낮춤).
d2 = yaml.safe_load(open(base))
cs = d2['controller_server']['ros__parameters']
cs['general_goal_checker']['xy_goal_tolerance'] = 0.10
cs['FollowPath']['xy_goal_tolerance'] = 0.08
out4 = out.replace('_mppi.yaml', '_tol010.yaml')
open(out4, 'w').write('# GENERATED by make_variants.sh: nav2_params.yaml with goal tolerance 0.10 / DWB 0.08 -- do not edit\n'
                      + yaml.safe_dump(d2, sort_keys=False))
print('wrote', out4)
PY
